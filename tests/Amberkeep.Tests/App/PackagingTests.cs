using System.Buffers.Binary;
using Amberkeep.App.Platform;
using Amberkeep.App.ViewModels;
using Amberkeep.App.Views;

namespace Amberkeep.Tests.App;

/// <summary>Icon, version, licenses: what ships with the program (SPEC chapter 7).</summary>
public sealed class PackagingTests : IDisposable
{
    private static readonly byte[] PngSignature = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A];

    private readonly AppFixture _app = new();

    public void Dispose() => _app.Dispose();

    [Fact]
    public void Ico_file_lists_every_image_with_its_size_and_offset()
    {
        int[] sizes = [16, 32, 255, 256];
        var images = sizes.Select(s => (s, FakePng(s))).ToList();
        using var stream = new MemoryStream();

        IcoWriter.Write(stream, images);
        var ico = stream.ToArray();

        Assert.Equal(0, BinaryPrimitives.ReadUInt16LittleEndian(ico));
        Assert.Equal(1, BinaryPrimitives.ReadUInt16LittleEndian(ico.AsSpan(2)));
        Assert.Equal(sizes.Length, BinaryPrimitives.ReadUInt16LittleEndian(ico.AsSpan(4)));
        var expectedOffset = 6 + 16 * sizes.Length;
        for (var i = 0; i < sizes.Length; i++)
        {
            var entry = ico.AsSpan(6 + 16 * i, 16);
            var stored = sizes[i] == 256 ? 0 : sizes[i];
            Assert.Equal(stored, entry[0]);
            Assert.Equal(stored, entry[1]);
            Assert.Equal(1, BinaryPrimitives.ReadUInt16LittleEndian(entry[4..]));
            Assert.Equal(32, BinaryPrimitives.ReadUInt16LittleEndian(entry[6..]));
            var length = BinaryPrimitives.ReadInt32LittleEndian(entry[8..]);
            var offset = BinaryPrimitives.ReadInt32LittleEndian(entry[12..]);
            Assert.Equal(images[i].Item2.Length, length);
            Assert.Equal(expectedOffset, offset);
            Assert.Equal(images[i].Item2, ico.AsSpan(offset, length).ToArray());
            expectedOffset += length;
        }

        Assert.Equal(expectedOffset, ico.Length);
    }

    [Theory]
    [InlineData(0)]
    [InlineData(257)]
    public void Ico_rejects_sizes_outside_1_to_256(int size)
    {
        using var stream = new MemoryStream();
        Assert.Throws<ArgumentOutOfRangeException>(() => IcoWriter.Write(stream, [(size, FakePng(1))]));
    }

    [Fact]
    public void Ico_needs_at_least_one_image()
    {
        using var stream = new MemoryStream();
        Assert.Throws<ArgumentException>(() => IcoWriter.Write(stream, []));
    }

    [Fact]
    public void Shipped_icon_contains_png_images_from_16_to_256_pixels()
    {
        // The icon is generated by tools/Amberkeep.IconGen and embedded in the exe and the window.
        var ico = File.ReadAllBytes(Path.Combine(RepositoryRoot(), "src", "Amberkeep.App", "Assets", "amberkeep.ico"));

        var count = BinaryPrimitives.ReadUInt16LittleEndian(ico.AsSpan(4));
        var sizes = Enumerable.Range(0, count).Select(i => ico[6 + 16 * i] is 0 ? 256 : ico[6 + 16 * i]).ToList();
        Assert.Contains(16, sizes);
        Assert.Contains(32, sizes);
        Assert.Contains(48, sizes);
        Assert.Contains(256, sizes);
        for (var i = 0; i < count; i++)
        {
            var offset = BinaryPrimitives.ReadInt32LittleEndian(ico.AsSpan(6 + 16 * i + 12));
            Assert.Equal(PngSignature, ico.AsSpan(offset, PngSignature.Length).ToArray());
        }
    }

    [Fact]
    public async Task Logo_renders_at_every_icon_size() => await HeadlessApp.Session.Dispatch(
        () =>
        {
            foreach (var size in new[] { 16, 24, 25, 32, 64, 256 })
            {
                using var bitmap = LogoArt.Render(size);
                Assert.Equal(size, bitmap.PixelSize.Width);
                Assert.Equal(size, bitmap.PixelSize.Height);
            }

            var logo = new LogoView();
            Assert.Equal(40, logo.Width);
            Assert.NotNull(logo.Content);
        },
        TestContext.Current.CancellationToken);

    [Fact]
    public void Version_and_copyright_are_set()
    {
        var settings = new SettingsViewModel(_app.Shell);

        var version = typeof(SettingsViewModel).Assembly.GetName().Version!;
        Assert.Equal(version.ToString(3), settings.Version);
        Assert.True(version.Major >= 1);
        Assert.Equal("© 2026 LAMINATKAR", settings.Copyright);
        Assert.Contains("GNU General Public License v3", settings.LicenseText, StringComparison.Ordinal);
    }

    [Fact]
    public void Notices_contain_every_component_listed_in_About()
    {
        var notices = SettingsViewModel.ThirdPartyNotices();

        Assert.Contains("GNU General Public License", notices, StringComparison.Ordinal);
        foreach (var component in SettingsViewModel.Components)
        {
            // Each component has its own section with the full license text.
            Assert.Contains($"\n{component.Component}\n====", notices.ReplaceLineEndings("\n"), StringComparison.Ordinal);
            Assert.Contains(component.Url, notices, StringComparison.Ordinal);
        }
    }

    [Fact]
    public void Notices_file_and_license_are_in_the_repository()
    {
        var root = RepositoryRoot();
        var notices = File.ReadAllText(Path.Combine(root, "THIRD-PARTY-NOTICES.txt"));
        Assert.Equal(notices.ReplaceLineEndings(), SettingsViewModel.ThirdPartyNotices().ReplaceLineEndings());
        Assert.StartsWith("GNU GENERAL PUBLIC LICENSE", File.ReadAllText(Path.Combine(root, "LICENSE")).Trim(), StringComparison.Ordinal);
    }

    [Fact]
    public async Task View_licenses_shows_the_notices()
    {
        var settings = new SettingsViewModel(_app.Shell);

        await settings.ViewLicensesCommand.ExecuteAsync(null);

        var shown = Assert.Single(_app.Dialogs.Messages);
        Assert.StartsWith("Licenses: ", shown, StringComparison.Ordinal);
        Assert.Contains("Avalonia UI", shown, StringComparison.Ordinal);
    }

    private static byte[] FakePng(int seed) => [.. PngSignature, (byte)seed, (byte)(seed >> 8), 1, 2, 3];

    private static string RepositoryRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "Amberkeep.slnx")))
        {
            dir = dir.Parent;
        }

        return dir?.FullName ?? throw new InvalidOperationException("Repository root not found.");
    }
}
